package main

import (
	"context"
	"log"

	"worker/db"
	repository "worker/internal/repository"
)

func main() {
	ctx := context.Background()

	conn, err := db.Conn(ctx)

	if err != nil {
		log.Fatal("Erro ao conectar no PostgreSQL:", err)
	}

	defer conn.Close(ctx)
	repository.CleanupUsers(ctx, &conn)
}

